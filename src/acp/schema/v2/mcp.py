"""v2 MCP servers: transports clients pass on session setup, and MCP over ACP."""

from __future__ import annotations

from collections.abc import Sequence  # noqa: TC003
from typing import Annotated, Any, Literal

from pydantic import MISSING, Discriminator, Field, Tag

from acp.schema.v2.base import OTHER_TAG, AnnotatedObject, Schema, Unknown, open_discriminator
from acp.schema.v2.common import (  # noqa: TC001
    AbsolutePath,
    EnvVariable,
    HttpHeader,
    McpRequestId,
    McpServerAcpId,
)


class McpServerHttp(AnnotatedObject):
    """HTTP transport configuration for MCP."""

    type: Literal["http"] = Field(default="http", init=False)

    name: str
    """Human-readable name identifying this MCP server."""

    url: str
    """URL to the MCP server."""

    headers: Sequence[HttpHeader] | MISSING = MISSING
    """HTTP headers to set when making requests to the MCP server. Headers the MCP transport
    defines are owned by the transport, and Agents use the transport's values for them."""


class McpServerStdio(AnnotatedObject):
    """Stdio transport configuration for MCP."""

    type: Literal["stdio"] = Field(default="stdio", init=False)

    name: str
    """Human-readable name identifying this MCP server."""

    command: AbsolutePath
    """Absolute path to the MCP server executable."""

    args: Sequence[str] | MISSING = MISSING
    """Command-line arguments to pass to the MCP server."""

    env: Sequence[EnvVariable] | MISSING = MISSING
    """Environment variables to set when launching the MCP server. Names SHOULD be unique.
    Agents MAY reject duplicates with ``-32602``, and otherwise the last entry wins."""


class McpServerAcp(AnnotatedObject):
    """**UNSTABLE**: ACP transport configuration for MCP.

    The server is provided by an ACP component and talks over the ACP channel using
    ``mcp/message``.
    """

    type: Literal["acp"] = Field(default="acp", init=False)

    name: str
    """Human-readable name identifying this MCP server."""

    server_id: McpServerAcpId
    """Identifier generated by the component providing the server; never reused."""


class UnknownMcpServer(Unknown):
    """A custom or future MCP transport; ``type`` values starting with ``_`` are extensions."""

    type: str
    """The transport."""


McpServer = Annotated[
    Annotated[McpServerHttp, Tag("http")]
    | Annotated[McpServerAcp, Tag("acp")]
    | Annotated[McpServerStdio, Tag("stdio")]
    | Annotated[UnknownMcpServer, Tag(OTHER_TAG)],
    Discriminator(open_discriminator("type", frozenset({"http", "acp", "stdio"}))),
]
"""An MCP server the agent should connect to.

Each transport requires the matching ``session.mcp`` agent capability.
"""


# --- MCP over ACP (``mcp/message``) -------------------------------------------------


class MessageMcpRequest(AnnotatedObject):
    """**UNSTABLE**: Parameters of ``mcp/message``: an inner MCP request to the provider."""

    server_id: McpServerAcpId
    """The declared ACP MCP server receiving this request."""

    request_id: McpRequestId
    """The caller-generated identifier for the inner MCP request."""

    method: str
    """The inner MCP method name."""

    params: dict[str, Any] | MISSING | None = MISSING
    """The inner MCP params; ``None`` is the same as omitted."""


class MessageMcpNotification(AnnotatedObject):
    """**UNSTABLE**: Notification for an active inner MCP request, from provider to consumer."""

    server_id: McpServerAcpId
    """The declared ACP MCP server handling the associated request."""

    request_id: McpRequestId
    """The identifier of the active inner MCP request."""

    method: str
    """The inner MCP method name."""

    params: dict[str, Any] | MISSING | None = MISSING
    """The inner MCP params; ``None`` is the same as omitted."""


class McpError(Schema):
    """**UNSTABLE**: An inner MCP error, distinct from an outer ACP error."""

    code: int
    """Inner MCP error code. Never an ACP error code."""

    message: str
    """Inner MCP error message."""

    data: Any | MISSING = MISSING
    """Error data; an explicit ``None`` (``null``) is kept."""


class MessageMcpResult(AnnotatedObject):
    """**UNSTABLE**: Successful ``mcp/message`` outcome: an opaque inner MCP result."""

    result: Any
    """The inner MCP result; may be ``None`` (JSON ``null``)."""


class MessageMcpError(AnnotatedObject):
    """**UNSTABLE**: Successful ``mcp/message`` call whose inner MCP request failed."""

    error: McpError
    """The inner MCP error."""


MessageMcpResponse = MessageMcpResult | MessageMcpError
"""**UNSTABLE**: Response of ``mcp/message``: exactly one inner MCP outcome."""
